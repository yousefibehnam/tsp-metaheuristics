"""Markdown for results/RESULTS.md and results/pilot.md."""

from __future__ import annotations

ALGORITHMS = ("NN", "NN+2opt", "GA", "SA")
DESCRIPTION = {
    "NN": "nearest neighbour from a random start city",
    "NN+2opt": "the NN tour improved by best-improvement 2-opt until no move helps",
    "GA": "genetic algorithm, OX crossover + 2-opt mutation, random initial tours",
    "SA": "simulated annealing with 2-opt moves from a random tour",
}


def fmt_params(params: dict) -> str:
    return ", ".join(
        f"{k} = {v:g}" if isinstance(v, float) else f"{k} = {v}" for k, v in params.items()
    )


def markdown(results: dict) -> str:
    budget = results["evaluations"]
    seeds = results["seeds"]
    out = [
        "# Results",
        "",
        "Generated by `tspmh experiment` (`make experiment`). Every algorithm ran with seeds "
        f"{seeds[0]}–{seeds[-1]} ({len(seeds)} runs per instance). GA and SA each had a budget of "
        f"**{budget:,} tour evaluations** per run (GA: one per child; SA: one per proposed move).",
        "Gaps are relative to the proven optimum published in TSPLIB.",
        "",
        "| Algorithm | What it is |",
        "|---|---|",
        *[f"| {a} | {DESCRIPTION[a]} |" for a in ALGORITHMS],
        "",
        f"Parameters: GA {fmt_params(results['ga_params'])}, crossover rate 0.9, tournament of 3, "
        f"2 elites; SA {fmt_params(results['sa_params'])} (initial acceptance of an average uphill "
        "move, final / initial temperature), geometric cooling. Chosen by a pilot on other seeds "
        "([pilot.md](pilot.md)).",
        "",
        "## Summary: mean gap to the optimum over all runs",
        "",
        "| Instance | n | Optimum | " + " | ".join(ALGORITHMS) + " |",
        "|---|---|---|" + "---|" * len(ALGORITHMS),
    ]
    for name, entry in results["instances"].items():
        cells = [f"{entry['algorithms'][a]['mean_gap']:.2f} %" for a in ALGORITHMS]
        out.append(f"| {name} | {entry['n']} | {entry['optimum']:,} | " + " | ".join(cells) + " |")
    means = [
        sum(e["algorithms"][a]["mean_gap"] for e in results["instances"].values())
        / len(results["instances"])
        for a in ALGORITHMS
    ]
    out.append("| **mean** | | | " + " | ".join(f"**{m:.2f} %**" for m in means) + " |")
    out += ["", "![Convergence](convergence.png)", "", "![Best tours](tours.png)", ""]

    for name, entry in results["instances"].items():
        out += [
            f"## {name} ({entry['n']} cities, optimum {entry['optimum']:,})",
            "",
            f"*{entry['comment']}*",
            "",
            "| Algorithm | Mean ± sd | Best | Worst | Mean gap | Best gap | Optimal runs "
            "| Time per run |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for a in ALGORITHMS:
            s = entry["algorithms"][a]
            time = (
                f"{1000 * s['mean_seconds']:.0f} ms"
                if s["mean_seconds"] < 1
                else f"{s['mean_seconds']:.1f} s"
            )
            out.append(
                f"| {a} | {s['mean']:,.1f} ± {s['std']:,.1f} | {s['best']:,} | {s['worst']:,} | "
                f"{s['mean_gap']:.2f} % | {s['best_gap']:.2f} % | "
                f"{s['optimal_runs']}/{len(seeds)} | {time} |"
            )
        out.append("")
    return "\n".join(out)


def pilot_markdown(pilot: dict, chosen: dict) -> str:
    instances = pilot["instances"]
    out = [
        "# Parameter pilot",
        "",
        "Generated by `tspmh pilot`. Mean gap to the optimum (%) over seeds "
        f"{', '.join(map(str, pilot['seeds']))}, which are not used for the reported results, "
        f"with a budget of {pilot['evaluations']:,} tour evaluations. The setting with the lowest "
        "mean over both instances is used in the main experiment.",
        "",
    ]
    for algorithm in ("GA", "SA"):
        rows = [r for r in pilot["rows"] if r["algorithm"] == algorithm]
        out += [
            f"## {algorithm}",
            "",
            "| Parameters | " + " | ".join(instances) + " | Mean |",
            "|---|" + "---|" * (len(instances) + 1),
        ]
        for r in rows:
            mark = " **(chosen)**" if r["params"] == chosen[algorithm] else ""
            cells = " | ".join(f"{r['gaps'][i]:.2f}" for i in instances)
            out.append(f"| {fmt_params(r['params'])}{mark} | {cells} | {r['mean_gap']:.2f} |")
        out.append("")
    return "\n".join(out)
